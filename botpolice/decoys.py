"""Per-install decoy identity: randomized banners and device strings.

Fingerprintable constants — a fixed ``SSH-2.0-OpenSSH_9.8`` banner, a fixed ADB
device string, a fixed web-server header — make a decoy easy to recognize once
an attacker has seen one instance. This module produces a randomized identity
that is **stable across restarts** for a given install (so it does not itself
look suspicious), stored in a small JSON file and regenerated by the
``rotate-decoys`` command.

Everything here is inert data. The values are only ever sent to peers or logged;
they are never interpreted.
"""

