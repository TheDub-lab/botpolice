def _random_build_id() -> str:
    # AOSP-style build id, e.g. "TQ1A.230205.002" or "RKQ1.211001.001".
    letters = "".join(random.choice("ABCDEFGHJKLMNPQRSTUVWXYZ") for _ in range(3))
    return f"{letters}1A.{random.randint(100000, 999999)}.{random.randint(0, 999):03d}"


def _random_android_identity() -> dict[str, str]:
    profile = dict(random.choice(_DEVICE_PROFILES))
    release = random.choice(_ANDROID_RELEASES)
    build_id = _random_build_id()
    name = profile["ro.product.name"]
    device = profile["ro.product.device"]
    brand = profile["ro.product.brand"]
    fingerprint = (
        f"{brand}/{name}/{device}:{release}/{build_id}/"
        f"{secrets.token_hex(4)}:user/release-keys"
    )
    identity = {
        **profile,
        "ro.build.version.release": release,
        "ro.build.version.sdk": _ANDROID_SDK[release],
        "ro.build.type": "user",
        "ro.debuggable": "1",
        "ro.build.id": build_id,
        "ro.build.fingerprint": fingerprint,
        "features": _FEATURES,
    }
    return identity


def _random_ssh_banner() -> str:
    return f"SSH-2.0-OpenSSH_{random.choice(_OPENSSH_VERSIONS)}{random.choice(_OS_SUFFIXES)}"


@dataclass
class DecoyIdentity:
    """The randomized, install-stable decoy identity (all inert data)."""

    ssh_banner: str = "SSH-2.0-OpenSSH_9.8"
    http_server: str = "nginx/1.24.0"
    adb_identity: dict[str, str] = field(
        default_factory=lambda: dict(DEFAULT_ADB_IDENTITY)
    )

    @classmethod
    def default(cls) -> DecoyIdentity:
        return cls()

    @classmethod
    def random(cls) -> DecoyIdentity:
        return cls(
            ssh_banner=_random_ssh_banner(),
            http_server=random.choice(_HTTP_SERVERS),
            adb_identity=_random_android_identity(),
        )

    def to_dict(self) -> dict[str, Any]:
        return {
            "ssh_banner": self.ssh_banner,
            "http_server": self.http_server,
            "adb_identity": dict(self.adb_identity),
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any] | None) -> DecoyIdentity:
        data = data or {}
        identity = data.get("adb_identity")
        if not isinstance(identity, dict) or not identity:
            identity = dict(DEFAULT_ADB_IDENTITY)
        else:
            identity = {str(k): str(v) for k, v in identity.items()}
        ssh_banner = str(data.get("ssh_banner") or "SSH-2.0-OpenSSH_9.8")
        http_server = str(data.get("http_server") or "nginx/1.24.0")
        return cls(ssh_banner=ssh_banner, http_server=http_server, adb_identity=identity)


def load_identity(path: str | Path) -> DecoyIdentity | None:
    """Load a decoy identity from ``path``; return ``None`` if absent/invalid."""
    p = Path(path)
    try:
        with p.open("r", encoding="utf-8") as fh:
            doc = json.load(fh)
    except (OSError, ValueError):
        return None
    if not isinstance(doc, dict):
        return None
    return DecoyIdentity.from_dict(doc)


def save_identity(path: str | Path, identity: DecoyIdentity) -> None:
    """Atomically write ``identity`` to ``path``."""
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    tmp = p.with_suffix(p.suffix + ".tmp")
    with tmp.open("w", encoding="utf-8") as fh:
        json.dump(identity.to_dict(), fh, indent=2, sort_keys=True)
        fh.write("\n")
    tmp.replace(p)


def resolve_identity(config: Config) -> DecoyIdentity:
    """Resolve the decoy identity for a run.

    Precedence:

    1. explicit ``decoys.ssh_banner`` / ``decoys.http_server`` overrides;
    2. the identity stored in ``decoys.file`` (created on first run when
       ``decoys.auto_generate`` is true, giving each install a stable random
       identity);
    3. the built-in defaults.
    """
    path = config.resolve(config.decoys.file)
    identity = load_identity(path)
    if identity is None:
        if config.decoys.auto_generate:
            identity = DecoyIdentity.random()
            with contextlib.suppress(OSError):
                save_identity(path, identity)
        else:
            identity = DecoyIdentity.default()
    if config.decoys.ssh_banner:
        identity.ssh_banner = config.decoys.ssh_banner
    if config.decoys.http_server:
        identity.http_server = config.decoys.http_server
    return identity

